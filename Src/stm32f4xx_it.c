/**
  * @brief This function handles Hard fault interrupt.
  */
void HardFault_Handler(void)
{
  /* USER CODE BEGIN HardFault_IRQn 0 */
  /* Minimal fault beacon: polled UART + PA5, no HAL/tick dependency.
     If the console ever shows this, the fault is real (not a VCP drop). */
  GPIOA->BSRR = GPIO_PIN_5;
  {
    const char *p = "HARDFAULT\r\n";
    while (*p)
    {
      uint32_t to = 100000U;
      while (!(USART2->SR & USART_SR_TXE) && to > 0U)
      {
        to--;
      }
      USART2->DR = (uint16_t)(*p);
      p++;
    }
  }
  /* USER CODE END HardFault_IRQn 0 */
  while (1)
  {
    /* USER CODE BEGIN W1_HardFault_IRQn 0 */
    /* USER CODE END W1_HardFault_IRQn 0 */
  }
}

